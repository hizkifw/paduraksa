using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Conventions;
using Microsoft.EntityFrameworkCore.Metadata.Conventions.Infrastructure;
using Microsoft.Extensions.DependencyInjection;

namespace Paduraksa.Storage.Ids;

public static class TypedIdModelConfigurationBuilderExtensions
{
    /// <summary>
    /// Maps every typed ID (<c>ITypedId&lt;TSelf, TValue&gt;</c>) in the model, with no per-property configuration.
    /// Call from <see cref="DbContext.ConfigureConventions"/>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// IDs are found from the CLR types of the members EF discovers, so nothing has to be listed or scanned: EF's
    /// property discovery is extended to accept typed IDs (and their nullable forms) wherever it looks for scalar
    /// properties, i.e. entity types and complex types, including keys and foreign keys. As for any other scalar,
    /// a property needs a setter (any accessibility, possibly on a base type); computed properties stay unmapped.
    /// </para>
    /// <list type="bullet">
    /// <item>UuidV7/UuidV4 columns: 16-byte big-endian <c>BLOB</c>, so SQLite's byte order is time order, string order
    /// and <c>CompareTo</c> order.</item>
    /// <item>Int64Ordered columns: <c>INTEGER</c>. A single-column key is the table's rowid alias
    /// (<c>INTEGER PRIMARY KEY</c>, no <c>AUTOINCREMENT</c>).</item>
    /// <item>Inside JSON complex types (<c>ComplexProperty(...).ToJson()</c>): the canonical string (<c>host_…</c>), so
    /// the stored document reads like the API/export, and JSON members can be queried with a string parameter.</item>
    /// <item>Lists of IDs (<c>List&lt;RouteId&gt;</c>, arrays, …) are primitive collections: a JSON array of canonical
    /// strings, in their own column or inside a JSON document. <c>Contains</c> translates to <c>json_each</c>.</item>
    /// <item>Typed-ID properties are never generated by the database (<see cref="Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never"/>):
    /// IDs come from the typed-ID generators.</item>
    /// </list>
    /// <para>
    /// <b>Hard rule: an ID inside JSON never equals a column ID in SQL.</b> The JSON form is TEXT, the column form is
    /// a BLOB or INTEGER, so comparing or joining them (<c>h.Settings.FallbackHostId == h.Id</c>,
    /// <c>Routes.Any(r =&gt; r.Id == h.Settings.DefaultRouteId)</c>) silently matches nothing. References inside JSON
    /// settings are resolved in memory (by the snapshot compiler), never joined in SQL.
    /// </para>
    /// <para>
    /// Explicit configuration (<c>HasConversion</c>, <c>ValueGeneratedOnAdd</c>, …) still wins. Owned entity types
    /// mapped to JSON are rejected when the model is built; use complex types. In LINQ, compare IDs directly
    /// (<c>==</c>, <c>&lt;</c>, <c>CompareTo</c>, <c>Contains</c>, <c>OrderBy</c> all translate); <c>id.Value</c> can't be
    /// translated through a value converter.
    /// </para>
    /// </remarks>
    public static ModelConfigurationBuilder AddTypedIdConventions(this ModelConfigurationBuilder configurationBuilder)
    {
        ArgumentNullException.ThrowIfNull(configurationBuilder);
        configurationBuilder.Conventions.Replace<PropertyDiscoveryConvention>(
            services => new TypedIdPropertyDiscoveryConvention(services.GetRequiredService<ProviderConventionSetBuilderDependencies>()));
        configurationBuilder.Conventions.Add(_ => new TypedIdConvention());
        return configurationBuilder;
    }
}
