using System.Text;

using Paduraksa.Contracts.Config;

namespace Paduraksa.Tests.Unit.Settings;

/// <summary>
/// The user guide's table of server settings (docs/guide/server-settings.md) is the catalogue's, so a new or changed setting can't leave the
/// guide behind. <c>PADURAKSA_UPDATE_DOCS=1</c> writes the table between its markers.
/// </summary>
public sealed class ServerSettingsGuideTests
{
    private const string Start = "<!-- server-settings:start (generated by ServerSettingsGuideTests) -->";
    private const string End = "<!-- server-settings:end -->";

    private static string GroupTitle(ServerSettingGroup group) => group switch
    {
        ServerSettingGroup.Retention => "Data retention",
        ServerSettingGroup.SignIn => "Sign-in",
        ServerSettingGroup.Notifications => "Notifications",
        ServerSettingGroup.Integrations => "Integrations",
        _ => "Connections",
    };

    private static string Table()
    {
        StringBuilder text = new();
        text.Append("| Setting | Environment variable | Default | Accepted | Applies |\n|---|---|---|---|---|\n");
        foreach (var group in ServerSettingCatalog.All.GroupBy(s => s.Group))
        {
            foreach (var setting in group)
            {
                var range = setting.MinText is { } min && setting.MaxText is { } max
                    ? $"{ServerSettingText.Describe(setting.Kind, min)} to {ServerSettingText.Describe(setting.Kind, max)}"
                    : setting is TextServerSetting words ? words.Accepted : "on or off";
                var applies = setting.Apply == ServerSettingApply.Live ? "live" : "after a restart";
                text.Append($"| {GroupTitle(group.Key)}: {setting.Section}, {setting.Title} | `{setting.EnvironmentVariable}` | {ServerSettingText.Describe(setting.Kind, setting.DefaultText)} (`{(setting.DefaultText.Length == 0 ? "\"\"" : setting.DefaultText)}`) | {range} | {applies} |\n");
            }
        }

        return text.ToString();
    }

    private static string GuidePath()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "Paduraksa.slnx")))
            {
                return Path.Combine(dir.FullName, "docs", "guide", "server-settings.md");
            }
        }

        throw new InvalidOperationException("Paduraksa.slnx not found");
    }

    [Fact]
    public void TheGuidesTableIsTheCatalogues()
    {
        var path = GuidePath();
        var guide = File.ReadAllText(path).ReplaceLineEndings("\n");
        var start = guide.IndexOf(Start, StringComparison.Ordinal);
        var end = guide.IndexOf(End, StringComparison.Ordinal);
        Assert.True(start >= 0 && end > start, "the guide has the table's markers");
        var expected = guide[..(start + Start.Length)] + "\n\n" + Table() + "\n" + guide[end..];
        if (Environment.GetEnvironmentVariable("PADURAKSA_UPDATE_DOCS") == "1")
        {
            File.WriteAllText(path, expected);
            return;
        }

        Assert.True(expected == guide, "docs/guide/server-settings.md is behind the catalogue; regenerate it: PADURAKSA_UPDATE_DOCS=1 dotnet test --project tests/Paduraksa.Tests.Unit --filter-class \"*ServerSettingsGuideTests\"");
    }
}
